// POST /api/chat
app.post("/api/chat", async (req: Request, res: Response) => {
  try {
    const { messages } = req.body;

    if (!Array.isArray(messages) || messages.length === 0) {
      res.status(400).json({ error: "Missing or invalid 'messages' array" });
      return;
    }

    const latestUserMessage =
      [...messages].reverse().find((m) => m.role === "user")?.content || "";

    const ai = getAIClient();

    if (!ai) {
      // If GEMINI_API_KEY is not configured, reply with grounded document answer
      const answer = generateDocumentAnswer(latestUserMessage);
      res.json({ reply: answer });
      return;
    }

    // Format conversation history for Gemini SDK
    const contents = messages.map((m: { role: string; content: string }) => ({
      role: m.role === "assistant" || m.role === "model" ? "model" : "user",
      parts: [{ text: m.content }],
    }));

    const response = await ai.models.generateContent({
      model: "gemini-3.8-flash",
      contents: contents,
      config: {
        systemInstruction: DOCUMENT_SYSTEM_INSTRUCTION,
        temperature: 0.1, // Low temperature to eliminate hallucination
      },
    });

    const replyText = response.text || generateDocumentAnswer(latestUserMessage);
    res.json({ reply: replyText });
  } catch (error: any) {
    console.error("Gemini API Chat Error:", error);
    // Graceful fallback to document answer with WhatsApp reference when unable to answer
    const latestUserMessage =
      req.body?.messages?.[req.body.messages.length - 1]?.content || "";
    const fallbackAnswer = generateDocumentAnswer(latestUserMessage);
    res.json({ reply: fallbackAnswer });
  }
});

