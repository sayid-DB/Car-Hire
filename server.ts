// Admin Authentication Checker
function checkAdminAuth(req: Request): boolean {
  const pinHeader = req.headers["x-admin-pin"] as string | undefined;
  const pinQuery = req.query.pin as string | undefined;
  const provided = pinHeader || pinQuery;
  return Boolean(provided && provided === ADMIN_PIN);
}

// Nodemailer Transporter Helper
function getEmailTransporter() {
  if (process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASS) {
    return nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: Number(process.env.SMTP_PORT) || 587,
      secure: Number(process.env.SMTP_PORT) === 465,
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    });
  }
  return null;
}

